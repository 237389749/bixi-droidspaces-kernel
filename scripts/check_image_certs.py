#!/usr/bin/env python3
"""Check that a built kernel Image embeds the expected X.509 certificate.

The stock GKI modules are signed by the vendor build's "Build time
autogenerated kernel key".  A custom kernel that does not trust that key
treats those modules as vendor modules (sig_ok=false), and the GKI protected
symbol check then rejects rfkill/cfg80211/qmi/rmnet with -EACCES.

Usage:
    check_image_certs.py Image <sha256-fingerprint> [more fingerprints...]

Fingerprint format: AA:BB:... or aabb... (case-insensitive).
Exit 1 if any expected certificate is missing.
"""

import hashlib
import re
import sys

# SEQUENCE { SEQUENCE (tbsCertificate) { [0] { INTEGER 2 } ... }
_CERT_RE = re.compile(rb"\x30\x82(..)\x30\x82(..)\xa0\x03\x02\x01\x02", re.S)


def find_der_certs(data):
    for match in _CERT_RE.finditer(data):
        outer = int.from_bytes(match.group(1), "big") + 4
        inner = int.from_bytes(match.group(2), "big") + 4
        if inner < outer < 16384:
            yield data[match.start() : match.start() + outer]


def normalize(fingerprint):
    return fingerprint.replace(":", "").replace(" ", "").lower()


def main(argv):
    if len(argv) < 3:
        print(__doc__.strip())
        return 2

    data = open(argv[1], "rb").read()
    expected = {normalize(f) for f in argv[2:]}
    found = {hashlib.sha256(der).hexdigest() for der in find_der_certs(data)}

    print(f"certificates in image: {len(found)}")
    for fpr in sorted(found):
        print(f"  {':'.join(fpr[i:i+2] for i in range(0, len(fpr), 2)).upper()}")

    missing = expected - found
    if missing:
        print("MISSING expected certificate(s):")
        for fpr in sorted(missing):
            print(f"  {fpr}")
        return 1

    print("OK: all expected certificates are embedded")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
